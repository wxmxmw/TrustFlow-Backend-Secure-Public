CREATE EXTENSION IF NOT EXISTS VECTOR;

CREATE TABLE IF NOT EXISTS USERS (
  USER_ID BIGSERIAL PRIMARY KEY,
  USERNAME VARCHAR(255),
  WALLET_ADDRESS VARCHAR(128) NOT NULL UNIQUE,
  NONCE VARCHAR(255) NOT NULL,
  CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS DOCUMENTS (
  DOC_ID BIGSERIAL PRIMARY KEY,
  USER_ID BIGINT NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  FILE_NAME VARCHAR(512) NOT NULL,
  MIME_TYPE VARCHAR(128) NOT NULL,
  FILE_SIZE BIGINT NOT NULL,
  FILE_PATH VARCHAR(1024) NOT NULL,
  FILE_HASH CHAR(64) NOT NULL,
  TX_HASH VARCHAR(128),
  STATUS VARCHAR(32) NOT NULL CHECK (STATUS IN ('processing', 'indexed', 'failed')),
  UPLOAD_TIME TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS IDX_DOCUMENTS_USER_ID ON DOCUMENTS(USER_ID);

CREATE INDEX IF NOT EXISTS IDX_DOCUMENTS_FILE_HASH ON DOCUMENTS(FILE_HASH);

CREATE TABLE IF NOT EXISTS DOCUMENT_CHUNKS (
  CHUNK_ID BIGSERIAL PRIMARY KEY,
  DOC_ID BIGINT NOT NULL REFERENCES DOCUMENTS(DOC_ID) ON DELETE CASCADE,
  CONTENT_TEXT TEXT NOT NULL,
  PAGE_NUMBER INT,
  EMBEDDING_VECTOR VECTOR(1536),
  CHUNK_HASH CHAR(64) NOT NULL
);

CREATE INDEX IF NOT EXISTS IDX_DOCUMENT_CHUNKS_DOC_ID ON DOCUMENT_CHUNKS(DOC_ID);

CREATE INDEX IF NOT EXISTS IDX_DOCUMENT_CHUNKS_EMBEDDING ON DOCUMENT_CHUNKS USING IVFFLAT (EMBEDDING_VECTOR VECTOR_COSINE_OPS) WITH (LISTS = 100);

CREATE TABLE IF NOT EXISTS SESSIONS (
  SESSION_ID BIGSERIAL PRIMARY KEY,
  USER_ID BIGINT NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  TITLE VARCHAR(255),
  LATEST_TX_HASH VARCHAR(128),
  CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS IDX_SESSIONS_USER_ID ON SESSIONS(USER_ID);

DROP TABLE IF EXISTS GENERATION_RECORDS CASCADE;

CREATE TABLE IF NOT EXISTS GENERATION_RECORDS (
  RECORD_ID BIGSERIAL PRIMARY KEY,
  SESSION_ID BIGINT NOT NULL REFERENCES SESSIONS(SESSION_ID) ON DELETE CASCADE,
  ROLE VARCHAR(16) NOT NULL CHECK (ROLE IN ('user', 'assistant')),
  CONTENT_TYPE VARCHAR(16) NOT NULL CHECK (CONTENT_TYPE IN ('text', 'image')),
  PARENT_TX_HASH VARCHAR(128),
  CONTENT TEXT NOT NULL,
  ARTIFACT_URL VARCHAR(1024),
  MODEL_NAME VARCHAR(128),
  PARAMETERS JSON,
  CONTENT_HASH CHAR(64),
  TX_HASH VARCHAR(128),
  WATERMARK_INFO JSON,
  CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS IDX_GENERATION_RECORDS_SESSION_ID ON GENERATION_RECORDS(SESSION_ID);

CREATE INDEX IF NOT EXISTS IDX_GENERATION_RECORDS_TX_HASH ON GENERATION_RECORDS(TX_HASH);

CREATE INDEX IF NOT EXISTS IDX_GENERATION_RECORDS_CONTENT_HASH ON GENERATION_RECORDS(CONTENT_HASH);

CREATE TABLE IF NOT EXISTS CITATIONS (
  CITATION_ID BIGSERIAL PRIMARY KEY,
  RECORD_ID BIGINT NOT NULL REFERENCES GENERATION_RECORDS(RECORD_ID) ON DELETE CASCADE,
  DOC_ID BIGINT NOT NULL REFERENCES DOCUMENTS(DOC_ID) ON DELETE CASCADE,
  CHUNK_ID BIGINT NOT NULL REFERENCES DOCUMENT_CHUNKS(CHUNK_ID) ON DELETE CASCADE,
  SCORE DOUBLE PRECISION NOT NULL
);

CREATE INDEX IF NOT EXISTS IDX_CITATIONS_RECORD_ID ON CITATIONS(RECORD_ID);

CREATE INDEX IF NOT EXISTS IDX_CITATIONS_DOC_ID ON CITATIONS(DOC_ID);

DROP TABLE IF EXISTS VERIFICATION_LOGS CASCADE;

CREATE TABLE IF NOT EXISTS VERIFICATION_LOGS (
  LOG_ID BIGSERIAL PRIMARY KEY,
  VERIFIED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  INPUT_TYPE VARCHAR(16) NOT NULL CHECK (INPUT_TYPE IN ('text', 'image')),
  UPLOADED_FILE_PATH VARCHAR(1024),
  EXTRACTED_WATERMARK VARCHAR(128),
  VERIFIER_IP VARCHAR(64),
  UPLOADED_CONTENT_HASH CHAR(64),
  MATCHED_TX_HASH VARCHAR(128),
  SIMILARITY_SCORE DOUBLE PRECISION,
  STATUS VARCHAR(20) NOT NULL CHECK (STATUS IN ('success', 'tampered', 'no_watermark'))
);

CREATE INDEX IF NOT EXISTS IDX_VERIFICATION_LOGS_UPLOADED_HASH ON VERIFICATION_LOGS(UPLOADED_CONTENT_HASH);

